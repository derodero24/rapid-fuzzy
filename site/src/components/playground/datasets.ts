function identifiers(count: number): string[] {
  return Array.from({ length: count }, (_, i) => {
    const first = WORDS[i % WORDS.length];
    const second = WORDS[(i * 7) % WORDS.length];
    return `${first}_${second}_${i}`;
  });
}

